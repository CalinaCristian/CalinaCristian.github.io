import assert from 'node:assert/strict';
import fs from 'node:fs';
import { MENU_ORDER, MENU_AVAILABLE, RECOMMENDED_SPOTS, activityAvailable, touristTarget } from '../../src/spot-availability.js';
import { ACHIEVEMENTS } from '../../src/data.js';
const text=fs.readFileSync(new URL('../../src/spots/index.js',import.meta.url),'utf8');
const block=text.split('export const SPOTS_ALL = [')[1].split('\n];')[0];
const {all}=await import('data:text/javascript;base64,'+Buffer.from('export const all=['+block+'\n];').toString('base64'));
const visible=MENU_ORDER.map(id=>all.find(s=>s.id===id));
assert.equal(new Set(MENU_ORDER).size,MENU_ORDER.length);assert(visible.every(Boolean));
assert.deepEqual([...RECOMMENDED_SPOTS],MENU_ORDER);
assert.equal(visible.length,7);
for(const area of ['bucharest','seattle','bellevue']) assert(visible.filter(s=>(s.area || s.city)===area).length<=3);
for(const id of ['mopop','chihuly','gas-works','waterfront','stavropoleos-cec','athenaeum-revolution','spring-palace']) assert(!MENU_AVAILABLE.has(id));
assert(!activityAvailable({activity:'old-town-lipscani:shoteria-shot'}));
assert.equal(touristTarget('postcards-all',24,visible),visible.length);
assert.equal(touristTarget('spots-buc',10,visible)+touristTarget('spots-sea',14,visible),visible.length);
assert.equal(touristTarget('tours-buc',10,visible),visible.filter(s=>s.city==='bucharest').length);
assert.equal(touristTarget('unrelated',7,visible),7);assert.equal(touristTarget('spots-buc',10,null),10);
assert(!activityAvailable({activity:'herastrau-park:boat'}));assert(activityAvailable({activity:'old-town-lipscani:carusel'}));assert(activityAvailable({activity:'*:bike'}));
const oldSavedVisits=new Set(all.map(s=>s.id)),oldSavedUnlocks=new Set([...ACHIEVEMENTS.map(a=>a.id),'lm-needle-360','lm-bbg-plants']);
assert.equal(visible.filter(s=>oldSavedVisits.has(s.id)).length,visible.length);
assert(!ACHIEVEMENTS.some(a=>['lm-needle-360','lm-bbg-plants'].includes(a.id)));
assert(ACHIEVEMENTS.filter(a=>activityAvailable(a)).every(a=>oldSavedUnlocks.has(a.id)));
assert(!MENU_AVAILABLE.has('herastrau-park'));assert(!MENU_AVAILABLE.has('village-museum'));
console.log('Menu favorites, actual registry identities, available-city/postcard targets, unavailable activities and legacy retired-save controls passed.');
