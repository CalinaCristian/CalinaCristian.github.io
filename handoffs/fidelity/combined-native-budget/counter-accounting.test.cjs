'use strict';
const assert = require('node:assert/strict');
const { accountFrame, summarizeDraws } = require('./counter-accounting.cjs');
const zero = { calls: 0, triangles: 0 };
const draws = [{ pass: 'main', calls: 310, triangles: 1100000 }, { pass: 'mirror', calls: 48, triangles: 220000 }, { pass: 'true-shadow', calls: 28, triangles: 130000 }, { pass: 'reflection', calls: 8, triangles: 1056 }];
const sum = summarizeDraws(draws);
assert.deepEqual(sum.measured, { calls: 394, triangles: 1451056 });
assert.equal(sum.passes.reflection.triangles, 1056);
const clean = accountFrame(zero, zero, sum.measured, draws);
assert.equal(clean.rawStatsAgreement, true);
assert.equal(clean.measuredFrameOverBudget, false);
const carried = accountFrame({ calls: 27, triangles: 3000 }, zero, { calls: 421, triangles: 1454056 }, draws);
assert.equal(carried.rawStatsAgreement, true);
assert.equal(carried.rawStatsOverBudget, true);
assert.equal(carried.measuredFrameOverBudget, false);
assert.equal(carried.measuredCompleteFrame.calls, 394);
assert.equal(carried.observedPriorCounterCarry.calls, 27);
const inconsistent = accountFrame({ calls: 27, triangles: 3000 }, zero, { calls: 427, triangles: 1454056 }, draws);
assert.equal(inconsistent.rawStatsAgreement, false);
assert.equal(inconsistent.measuredCompleteFrame.calls, 394, 'Raw stats must never be used to infer an unobserved frame count');
const over = accountFrame(zero, zero, { calls: 402, triangles: 1452112 }, [...draws, { pass: 'reflection', calls: 8, triangles: 1056 }]);
assert.equal(over.rawStatsAgreement, true);
assert.equal(over.measuredFrameOverBudget, true, 'Actual warm/reflection work must remain in the budget');
assert.equal(accountFrame(zero, { calls: 1, triangles: 2 }, sum.measured, draws).productionEndResetObserved, false);
console.log(JSON.stringify({ passed: true, controls: 6, scope: 'Independent observed-draw sums, prior carry, raw-stat reconciliation, mismatch retention, real reflection over-cap and end-reset observation' }));
