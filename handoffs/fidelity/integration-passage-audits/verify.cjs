const fs = require('node:fs'), path = require('node:path'), zlib = require('node:zlib'), assert = require('node:assert/strict');
const read = name => JSON.parse(zlib.gunzipSync(fs.readFileSync(path.join(__dirname, 'proof', name + '.json.gz'))));
const before = read('before'), after = read('after'), rows = after.districts.flatMap(d => d.results);
assert.equal(rows.length, 5); assert(rows.every(r => r.ok && r.maxSourceProgressM > r.sourceLengthM + 1.5));
assert.equal(after.errors.length, 0); assert(after.summary.pass);
const issues = after.districts.flatMap(d => d.rawHarnessIssues);
assert.equal(issues.filter(i => i.severity !== 'low').length, 0);
assert(before.districts.flatMap(d => d.rawHarnessIssues).filter(i => i.type === 'clipping' && i.severity === 'high').length >= 4);
const controls = rows.flatMap(r => r.sourceControls);
assert.equal(controls.length, 5);
for (const c of controls) assert(c.opening.clear && c.post.solid && c.ceiling.solid && c.roof.belowSolid && c.roof.aboveClear);
console.log(JSON.stringify({ crossings: 5, nativeSourceAssertions: 25, high: 0, medium: 0, low: issues.length, errors: 0 }));
