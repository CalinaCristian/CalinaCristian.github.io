#!/usr/bin/env python3
"""Exact box-filter coverage of the union of the unchanged authored polygons.

Split scanline integration at polygon vertices, edge crossings and texel borders.
Within each band the union boundaries are linear and cross no texel boundaries,
so midpoint integration gives the exact polygon/texel intersection area.
"""
import base64
import json
import math
from pathlib import Path
import subprocess
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
source = "import {dinamoPaintSegments,paintPolygon} from './game/src/landmark-pitch-paint.js'; console.log(JSON.stringify(dinamoPaintSegments().map(paintPolygon)));"
polygons = json.loads(subprocess.check_output(['node', '--input-type=module', '-e', source], cwd=ROOT))
size = 1024
polygons = [[((u + 54) / 108 * size, (v + 34.5) / 69 * size) for u, v in p] for p in polygons]
edges = [(p[i], p[(i + 1) % len(p)]) for p in polygons for i in range(len(p))]
knots = set(float(y) for y in range(size + 1))
for a, b in edges:
    knots.update([a[1], b[1]])
    if abs(b[0] - a[0]) > 1e-12:
        for x in range(math.ceil(min(a[0], b[0])), math.floor(max(a[0], b[0])) + 1):
            knots.add(a[1] + (b[1] - a[1]) * (x - a[0]) / (b[0] - a[0]))
for i, (a, b) in enumerate(edges):
    dx, dy = b[0] - a[0], b[1] - a[1]
    for c, d in edges[i + 1:]:
        ex, ey = d[0] - c[0], d[1] - c[1]
        determinant = dx * ey - dy * ex
        if abs(determinant) < 1e-12:
            continue
        t = ((c[0] - a[0]) * ey - (c[1] - a[1]) * ex) / determinant
        u = ((c[0] - a[0]) * dy - (c[1] - a[1]) * dx) / determinant
        if 0 < t < 1 and 0 < u < 1:
            knots.add(a[1] + t * dy)
knots = sorted(k for k in knots if 0 <= k <= size)
coverage = np.zeros((size, size), dtype=float)
for lo, hi in zip(knots, knots[1:]):
    y, intervals = (lo + hi) / 2, []
    if hi - lo < 1e-12:
        continue
    for p in polygons:
        crossings = []
        for a, b in zip(p, p[1:] + p[:1]):
            if min(a[1], b[1]) < y < max(a[1], b[1]):
                crossings.append(a[0] + (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]))
        if crossings:
            intervals.append([min(crossings), max(crossings)])
    merged = []
    for a, b in sorted(intervals):
        if merged and a <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    for a, b in merged:
        first, last, row, height = math.floor(a), math.floor(b), math.floor(y), hi - lo
        if first == last:
            coverage[row, first] += (b - a) * height
        else:
            coverage[row, first] += (first + 1 - a) * height
            coverage[row, first + 1:last] += height
            coverage[row, last] += (b - last) * height
assert coverage.min() >= -1e-8 and coverage.max() <= 1 + 1e-8
alpha = np.rint(np.clip(coverage, 0, 1) * 255).astype(np.uint8).ravel()
packed = bytearray()
i = 0
while i < len(alpha):
    value, end = int(alpha[i]), i + 1
    while end < min(len(alpha), i + 65535) and alpha[end] == value:
        end += 1
    count = end - i
    packed.extend([count // 256, count % 256, value])
    i = end
asset = ROOT / 'game/src/landmark-pitch-paint-coverage.js'
asset.write_text('// Generated by tools/landmarks/generate-pitch-paint.py; do not edit by hand.\n'
                 '// Unchanged authored 12 cm polygon union; exact texel-area coverage, 1024 squared.\n'
                 "export const DINAMO_PAINT_COVERAGE = '" + base64.b64encode(packed).decode() + "';\n")
print(json.dumps({'assetBytes': asset.stat().st_size, 'exactUnionAreaM2': float(coverage.sum()) * 108 * 69 / size**2, 'quantizedAreaM2': float(alpha.sum()) / 255 * 108 * 69 / size**2, 'nonzeroTexels': int(np.count_nonzero(alpha))}))
