#!/usr/bin/env node
// Source footbridges without regenerating a district: writes one dataset's records into game/src/footbridge-sources.js.
//
//   node tools/osm/add-footbridges.mjs --data game/data/<city>-<district>.json --osm <overpass.json> [--out game/src/footbridge-sources.js] [--margin 100] [--dry]
//
// <overpass.json> is an Overpass `out body geom;` result covering the district (ways need `nodes` and `geometry`).
// Selected: every way with highway=footway|path|pedestrian|cycleway and a `bridge` tag (not `no`) whose middle lies inside
// the dataset's road-graph bounds grown by --margin metres, plus the highway=steps ways that share an end node with it.
// The district JSON is only read (projection, bounds). Records keep the literal source: way id, node ids, every raw tag,
// and the projected points in game metres (x east, z south, 2 decimals). No height is inferred here; the renderer
// documents the deck level it assumes (game/src/elevated-sources.js). Re-running replaces only that dataset's key.
import fs from 'node:fs';
import path from 'node:path';
const arg = (k, d) => { const i = process.argv.indexOf(`--${k}`); return i < 0 ? d : (process.argv[i + 1] == null || process.argv[i + 1].startsWith('--') ? true : process.argv[i + 1]); };
const dataFile = arg('data'), osmFile = arg('osm'), outFile = arg('out', 'game/src/footbridge-sources.js'), margin = Number(arg('margin', 100)), dry = !!arg('dry', false);
if (!dataFile || !osmFile) { console.error('usage: add-footbridges.mjs --data <district.json> --osm <overpass.json> [--out <module.js>] [--margin 100] [--dry]'); process.exit(2); }
const data = JSON.parse(fs.readFileSync(dataFile, 'utf8')), key = path.basename(dataFile, '.json'), P = data.proj;
if (!P || P.compress) { console.error('refusing: this tool supports only an uncompressed district projection'); process.exit(1); }
const proj = g => [Math.round((g.lon - P.lon0) * P.mPerLon * P.scale * 100) / 100, Math.round(-(g.lat - P.lat0) * P.mPerLat * P.scale * 100) / 100];
const [x0, z0, x1, z1] = data.bounds.map(v => v / 10);
const inside = ([x, z]) => x >= x0 - margin && x <= x1 + margin && z >= z0 - margin && z <= z1 + margin;
const ways = JSON.parse(fs.readFileSync(osmFile, 'utf8')).elements.filter(e => e.type === 'way' && e.tags && e.nodes && e.geometry);
const record = w => ({ id: `w${w.id}`, tags: w.tags, nodeIds: w.nodes, points: w.geometry.map(proj) });
const steps = ways.filter(w => w.tags.highway === 'steps'), out = [];
for (const w of ways) {
    const t = w.tags;
    if (!/^(footway|path|pedestrian|cycleway)$/.test(t.highway || '') || !t.bridge || t.bridge === 'no') continue;
    const pts = w.geometry.map(proj), a = pts[0], b = pts[pts.length - 1];
    if (!inside([(a[0] + b[0]) / 2, (a[1] + b[1]) / 2])) continue;
    const ends = new Set([w.nodes[0], w.nodes[w.nodes.length - 1]]);
    out.push({ ...record(w), steps: steps.filter(s => ends.has(s.nodes[0]) || ends.has(s.nodes[s.nodes.length - 1])).map(record) });
}
out.sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
for (const b of out) console.log(`${b.id} ${JSON.stringify(b.points)} steps: ${b.steps.map(s => s.id).join(', ') || 'none'}`);
console.log(`${key}: ${out.length} footbridge(s)`);
if (dry) process.exit(0);
const HEAD = '// Generated by tools/osm/add-footbridges.mjs: OSM footway bridges (and the steps at their ends) per district dataset.\n// © OpenStreetMap contributors (ODbL). Points are game metres (x east, z south). Rendered by elevated-sources.js.\nexport const FOOTBRIDGE_SOURCES = ';
let all = {};
if (fs.existsSync(outFile)) { const s = fs.readFileSync(outFile, 'utf8'), i = s.indexOf('FOOTBRIDGE_SOURCES = '); if (i >= 0) all = JSON.parse(s.slice(i + 21).replace(/;\s*$/, '')); }
delete all[key]; if (out.length) all[key] = out;
const body = '{\n' + Object.keys(all).sort().map(k => `    ${JSON.stringify(k)}: [\n${all[k].map(r => '        ' + JSON.stringify(r)).join(',\n')}\n    ]`).join(',\n') + '\n}';
fs.writeFileSync(outFile, HEAD + body + ';\n');
