// Writes the pedestrian-plaza tables of tools/osm/pedestrian-plazas.mjs: one data module per district
// (game/src/pedestrian-plazas/<city>-<district>.js, each well under the 60 KB module budget of spec 22) and the index
// game/src/pedestrian-plazas.js that ground-review.js imports (PEDESTRIAN_PLAZAS keyed '<city>-<district>', in the
// order given).
import fs from 'node:fs';

const HEADER = (fetched) =>
    `// GENERATED by tools/osm/pedestrian-plazas.mjs on ${fetched} from the live OSM data (Overpass API; © OpenStreetMap contributors, ODbL):\n` +
    `// mapped pedestrian plazas per district (highway=pedestrian|footway area=yes, area:highway, place=square; ways and multipolygons).\n` +
    `// Rows [sourceId, 'paved' | 'grass', surface, name, rings ([lat, lon] outers and inners, even-odd)]. Read by ground-review.js.\n` +
    `// Re-run the tool to refresh; do not edit by hand.\n`;
const ident = (key) => key.replace(/-(\w)/g, (_, c) => c.toUpperCase());

/** root: URL of the repository root; out: { '<city>-<district>': rows }; fetched: 'YYYY-MM-DD' */
export function writePedestrianPlazas(root, out, fetched) {
    const dir = new URL('game/src/pedestrian-plazas/', root);
    fs.mkdirSync(dir, { recursive: true });
    for (const [key, rows] of Object.entries(out)) {
        fs.writeFileSync(new URL(`${key}.js`, dir), HEADER(fetched) + `// ${key} (index: game/src/pedestrian-plazas.js)\n` +
            `export default [\n${rows.map(r => '    ' + JSON.stringify(r) + ',').join('\n')}\n];\n`);
    }
    const keys = Object.keys(out);
    fs.writeFileSync(new URL('game/src/pedestrian-plazas.js', root), HEADER(fetched) +
        keys.map(k => `import ${ident(k)} from './pedestrian-plazas/${k}.js';`).join('\n') +
        `\n\nexport const PEDESTRIAN_PLAZAS_FETCHED = '${fetched}';\nexport const PEDESTRIAN_PLAZAS = {\n${keys.map(k => `    '${k}': ${ident(k)},`).join('\n')}\n};\n`);
}
