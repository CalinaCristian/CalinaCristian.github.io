// Live OSM tags of every place-of-worship building in the district packs (backlog r3-look-11, 2026-11-13).
//
// The packs keep a church's style, footprint, height and roof, but not its religion / denomination / roof material
// (buildingSourceTags holds raw tags only for a few kinds). This tool reads the `church` buildings of all district packs,
// fetches their ways' current tags from the OSM API 0.6 (`/ways.json?ways=…`, 50 per call) and writes
//   game/src/worship-source.js  — the tags worship.js reads (religion, denomination, building, roof / colour / material /
//                                 tower keys), one row per OSM way
// No geometry is read from the API: positions, footprints and heights stay the packs'.
//   node tools/osm/worship-source.mjs            (fetch and write)
import fs from 'node:fs';
import { readDistrictData } from './district-data.mjs';

const ROOT = new URL('../../', import.meta.url);
const DISTRICTS = ['bucharest-grozavesti', 'bucharest-unirii', 'bucharest-romana', 'bucharest-floreasca', 'bucharest-pipera', 'bucharest-otopeni', 'seattle-seatac', 'seattle-bellevue'];
const KEEP = /^(religion|denomination|building|amenity|roof:(shape|colour|material)|building:(colour|material)|colour|tower(:.*)?|man_made|historic|start_date|height|building:levels)$/;

const ids = new Set();
for (const d of DISTRICTS) {
    const data = readDistrictData(new URL(`game/data/${d}.bin.gz`, ROOT));
    data.buildings.forEach((b, i) => { const id = data.buildingIds?.[i]; if (data.styles[b[0]] === 'church' && /^w\d+$/.test(id || '')) ids.add(id); });
}
const list = [...ids].sort((a, b) => +a.slice(1) - +b.slice(1)), rows = {};
for (let k = 0; k < list.length; k += 50) {
    const chunk = list.slice(k, k + 50).map(s => s.slice(1)).join(',');
    const res = await fetch(`https://api.openstreetmap.org/api/0.6/ways.json?ways=${chunk}`, { headers: { 'User-Agent': 'drive-my-cv-osm-tools/1.0' } });
    if (!res.ok) throw new Error(`OSM API ${res.status} for ${chunk}`);
    for (const el of (await res.json()).elements) rows['w' + el.id] = Object.fromEntries(Object.entries(el.tags || {}).filter(([key]) => KEEP.test(key)).sort());
}
const fetched = new Date().toISOString().slice(0, 10);
const body = Object.entries(rows).map(([id, t]) => `    ${id}: ${JSON.stringify(t)},`).join('\n');
const out = `// GENERATED by tools/osm/worship-source.mjs on ${fetched} from the live OSM API 0.6 (© OpenStreetMap contributors, ODbL):\n` +
    `// the religion / denomination / roof and colour tags of every place-of-worship building way in the district packs.\n` +
    `// Read by worship.js (\`worshipClass\`). Re-run the tool to refresh; do not edit by hand.\n` +
    `export const WORSHIP_SOURCE_FETCHED = '${fetched}';\nexport const WORSHIP_SOURCE = {\n${body}\n};\n`;
fs.writeFileSync(new URL('game/src/worship-source.js', ROOT), out);
console.log(`${list.length} ways, ${Object.keys(rows).length} rows → game/src/worship-source.js`);
