import assert from 'node:assert/strict';
import * as THREE from '../../game/vendor/three.module.min.js';
import { makeSourceShoreSampler, sourceShoreAttribute } from '../../game/src/water-shore.js';
const outer = [[0, 0], [100, 0], [100, 100], [0, 100]], hole = [[40, 40], [60, 40], [60, 60], [40, 60]];
const plain = makeSourceShoreSampler([{ sourceId: 'outer', outer, holes: [] }]);
const island = makeSourceShoreSampler([{ sourceId: 'outer-with-island', outer, holes: [hole] }]);
for (const [p, expected] of [[[0, 50], 0], [[20, 20], 20], [[50, 50], 30], [[101, 50], 1]]) assert.equal(plain.distance(...p), expected);
for (const [p, expected] of [[[40, 50], 0], [[35, 50], 5], [[20, 50], 20], [[50, 50], 10]]) assert.equal(island.distance(...p), expected);
const position = new THREE.Float32BufferAttribute([0, 0, 0, 100, 0, 0, 100, 0, 100, 0, 0, 0, 4, 0, 0, 0, 0, 4, 40, 0, 45, 36, 0, 45, 40, 0, 49], 3);
const original = position.array.slice(), result = sourceShoreAttribute(position, null, plain);
assert.deepEqual(position.array, original);
assert.deepEqual([...result.distances.slice(0, 6)], [0, 0, 0, 0, 0, 0]);
assert.deepEqual([...result.foamReliable.slice(0, 6)], [0, 0, 0, 1, 1, 1]);
assert.equal(result.audit.coarseFoamOmittedFaces, 1);
assert.deepEqual(result.audit.coarseFoamOmittedFaceRanges, [[0, 1]]);
const holeResult = sourceShoreAttribute(position, null, island);
assert.deepEqual([...holeResult.distances.slice(6)], [0, 4, 0]);
assert.deepEqual([...holeResult.foamReliable.slice(6)], [1, 1, 1]);
const index = new THREE.Uint16BufferAttribute([0, 1, 2], 1), indexed = sourceShoreAttribute(position, index, plain);
assert.deepEqual([...index.array], [0, 1, 2]);
assert.equal(indexed.audit.indexedUnreliableFaces, 1); assert.equal(indexed.audit.coarseFoamOmittedFaces, 0);
const distant = makeSourceShoreSampler([{ sourceId: 'long', outer: [[-1e6, -1e6], [1e6, 1e6], [1e6, -1e6]], holes: [] }]);
assert.equal(distant.distance(0, 0), 0); assert.equal(distant.distance(-500, 500), 30);
console.log(JSON.stringify({ passed: true, exactOuterSamples: 4, exactInnerSamples: 4, coarseLocalFallbackFaces: result.audit.coarseFoamOmittedFaces, reliableHoleShoreSamples: 3, indexedIssueRetained: true, sourcePositionsAndIndicesUnchanged: true }));
